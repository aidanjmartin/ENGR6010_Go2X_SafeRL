"""Read the static boxes of the AEB Level 1 Gazebo world and measure them against the atrium square.

`aeb_level1.sdf` (tourbot, generated by dxf_to_gazebo.py) holds one static model whose links carry
`<collision name='<kind>_<n>_c'>` boxes with a `<pose>x y z roll pitch yaw</pose>` and `<size>`. Only the
collision boxes are read; each has a matching visual box with the same pose and size.
"""
import re
import xml.etree.ElementTree as ET
from dataclasses import asdict, dataclass

import numpy as np

NAME_RE = re.compile(r"^([a-z_]+?)_(\d+)_c$")


@dataclass
class Box:
    name: str
    kind: str
    x: float
    y: float
    z: float
    yaw: float
    sx: float
    sy: float
    sz: float

    def corners(self):
        c, s = np.cos(self.yaw), np.sin(self.yaw)
        local = np.array([[-1, -1], [1, -1], [1, 1], [-1, 1]]) * [self.sx / 2, self.sy / 2]
        return local @ np.array([[c, s], [-s, c]]) + [self.x, self.y]


def parse_boxes(sdf_text):
    """All collision boxes in the world, with their world poses (the models are static at the origin)."""
    root = ET.fromstring(sdf_text)
    boxes = []
    for model in root.iter("model"):
        mpose = model.find("pose")
        if mpose is not None and any(abs(float(v)) > 1e-9 for v in mpose.text.split()):
            raise ValueError(f"model {model.get('name')} has a non-zero pose; not handled")
        for col in model.iter("collision"):
            m = NAME_RE.match(col.get("name", ""))
            size = col.find("geometry/box/size")
            if m is None or size is None:
                continue
            x, y, z, roll, pitch, yaw = map(float, col.find("pose").text.split())
            if abs(roll) > 1e-6 or abs(pitch) > 1e-6:
                raise ValueError(f"{col.get('name')} is tilted; not handled")
            sx, sy, sz = map(float, size.text.split())
            boxes.append(Box(f"{m.group(1)}_{m.group(2)}", m.group(1), x, y, z, yaw, sx, sy, sz))
    return boxes


def _seg_dist(p, a, b):
    ab = b - a
    t = np.clip(np.dot(p - a, ab) / max(np.dot(ab, ab), 1e-12), 0.0, 1.0)
    return float(np.linalg.norm(p - (a + t * ab)))


def _cross(a, b):
    return a[..., 0] * b[..., 1] - a[..., 1] * b[..., 0]


def _inside(p, poly):
    """Point inside a counterclockwise convex polygon (boundary counts as inside)."""
    return all(_cross(poly[(i + 1) % len(poly)] - poly[i], p - poly[i]) >= -1e-12 for i in range(len(poly)))


def polygon_distance(P, Q):
    """Distance between two convex polygons; 0 when they touch or overlap."""
    if any(_inside(p, Q) for p in P) or any(_inside(q, P) for q in Q):
        return 0.0
    d = min(_seg_dist(p, Q[i], Q[(i + 1) % len(Q)]) for p in P for i in range(len(Q)))
    d = min(d, min(_seg_dist(q, P[i], P[(i + 1) % len(P)]) for q in Q for i in range(len(P))))
    if d < 1e-12:
        return 0.0
    # edge crossings without a vertex inside (two thin rectangles in a cross)
    for i in range(len(P)):
        for j in range(len(Q)):
            if _segments_cross(P[i], P[(i + 1) % len(P)], Q[j], Q[(j + 1) % len(Q)]):
                return 0.0
    return d


def _segments_cross(a, b, c, d):
    o = lambda p, q, r: np.sign(_cross(q - p, r - p))  # noqa: E731
    return o(a, b, c) * o(a, b, d) < 0 and o(c, d, a) * o(c, d, b) < 0


def square_polygon(center, side):
    h = side / 2
    cx, cy = center
    return np.array([[cx - h, cy - h], [cx + h, cy - h], [cx + h, cy + h], [cx - h, cy + h]])


def square_report(boxes, center, side, margin):
    """Distances of every box to the square, the boxes inside it, and the boxes within `margin` of its edge."""
    sq = square_polygon(center, side)
    c = np.asarray(center, float)
    rows = []
    for b in boxes:
        P = b.corners()
        d_edge = polygon_distance(P, sq)
        d_center = 0.0 if _inside(c, P) else min(_seg_dist(c, P[i], P[(i + 1) % 4]) for i in range(4))
        rows.append((d_center, d_edge, b))
    rows.sort(key=lambda r: r[0])
    near = [b for _, d, b in rows if d <= margin]
    return {
        "num_boxes": len(boxes),
        "inside_or_touching": [b.name for _, d, b in rows if d == 0.0],
        "nearest": [{"name": b.name, "distance_to_center_m": round(dc, 4), "distance_to_edge_m": round(de, 4)}
                    for dc, de, b in rows[:5]],
        "num_within_margin": len(near),
        "kinds_within_margin": {k: sum(b.kind == k for b in near) for k in sorted({b.kind for b in near})},
    }, near


def boxes_to_json(boxes):
    return [asdict(b) for b in boxes]
